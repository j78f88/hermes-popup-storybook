def main():
    bad = [k for k, rows in G.items() if len(rows) != 7 or len({len(r) for r in rows}) != 1]
    if bad:
        print("bad glyphs:", bad)
        return 1
    out = ROOT / "engine" / "library" / "font.json"
    out.write_text(json.dumps({"height": 7, "glyphs": G}, indent=1) + "\n")
    print(f"wrote {out} with {len(G)} glyphs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
